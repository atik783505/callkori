export type TKey = keyof typeof translations.en;
type ContextType = { lang: Lang; t: (k: TKey) => string; setLang: (l: Lang) => void };

const Ctx = createContext<ContextType>({
  lang: "en", t: (k) => translations.en[k] as string, setLang: () => {},
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = localStorage.getItem("ck_lang") as Lang | null;
    if (saved === "en" || saved === "bn") setLangState(saved);
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("ck_lang", l);
  };

  const t = (k: TKey): string => (translations[lang][k] as string) ?? (translations.en[k] as string);

  return <Ctx.Provider value={{ lang, t, setLang }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
